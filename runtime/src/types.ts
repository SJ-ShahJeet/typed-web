/**
 * `npm run types`: reads every spec.json in the registry and writes web.d.ts, one method per
 * site and type, so an agent reads one .d.ts and writes code against it (D9).
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { FieldSpec, Spec } from "./spec.ts";
import { camel, loadRegistry, lowerFirst } from "./web.ts";

const upperFirst = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

function tsType(field: FieldSpec): string {
  let t: string;
  switch (field.type) {
    case "string":
    case "date":
    case "url":
      t = "string";
      break;
    case "number":
      t = "number";
      break;
    case "boolean":
      t = "boolean";
      break;
    case "money":
      t = "Money";
      break;
    case "enum":
      t = field.values!.map((v) => JSON.stringify(v)).join(" | ");
      break;
  }
  if (field.sources.some((s) => s.kind === "css" && s.all)) t = `Array<${t}>`;
  return field.required ? t : `${t} | null`;
}

export function generateTypes(specs: Iterable<Spec>): string {
  const sites = new Map<string, Spec[]>();
  for (const spec of specs) (sites.get(spec.site) ?? sites.set(spec.site, []).get(spec.site)!).push(spec);

  const out: string[] = [
    "// Generated by `npm run types` from the registry. Do not edit; rerun after adding or repairing a spec.",
    'import type { CallOptions, Provenance, WebOptions } from "./src/web.ts";',
    'import type { Money } from "./src/coerce.ts";',
    "",
    "export type { CallOptions, Provenance, WebOptions, Money };",
    "export interface TypedRecord<T> { data: T; provenance: Provenance }",
    "",
  ];
  const members: string[] = [];
  for (const [site, list] of sites) {
    const methods: string[] = [];
    for (const spec of list) {
      const name = upperFirst(camel(site)) + spec.type;
      out.push(`/** ${site} v${spec.version}, schema.org ${spec.type}; fetched from ${spec.fetch.url} */`);
      out.push(`export interface ${name} {`);
      for (const [field, f] of Object.entries(spec.fields)) out.push(`  ${field}: ${tsType(f)};`);
      out.push("}", "");
      methods.push(`    ${lowerFirst(spec.type)}(id: string, opts?: CallOptions): Promise<TypedRecord<${name}>>;`);
    }
    members.push(`  ${camel(site)}: {`, ...methods, "  };");
  }
  out.push("export interface Web {", ...members, "  close(): void;", "}", "");
  out.push("export declare function createWeb(registryDir: string, opts?: WebOptions): Web;", "");
  return out.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const registry = process.argv[2];
  if (!registry) {
    console.error("usage: tsx src/types.ts <registryDir>");
    process.exit(2);
  }
  const specs = [...loadRegistry(registry).values()].map((s) => s.spec);
  const file = fileURLToPath(new URL("../web.d.ts", import.meta.url));
  writeFileSync(file, generateTypes(specs));
  console.error(`types: ${specs.length} spec(s) → ${file}`);
}
